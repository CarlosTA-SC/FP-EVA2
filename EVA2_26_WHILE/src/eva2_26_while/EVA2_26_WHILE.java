public class EVA2_26_WHILE {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        //1-10
        int i=1;
        while(i<=10){
            System.out.println(i + " - ");
            i++;
        }
        i = 10;
        while(i>=1){
            System.out.println(i + " - ");
            i--;
        }
    }
    
}
